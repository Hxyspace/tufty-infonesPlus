// Decode only the requested crop into the existing 320-wide UI framebuffer.
// Both settings previews share this Flash-resident sample without a RAM cache.
inline void draw_palette_sample(uint16_t *out,unsigned left,unsigned top,const uint16_t *colors,
                                unsigned sx=0,unsigned sy=0,unsigned width=256,unsigned height=240) {
    unsigned pixel=0;
    for(auto run:palette_sample) {
        const auto color=colors[run&63];
        for(unsigned n=0;n<unsigned(run>>6)+1;++n,++pixel) {
            const unsigned x=pixel%256,y=pixel/256;
            if(x>=sx && x<sx+width && y>=sy && y<sy+height)
                out[(top+y-sy)*320+left+x-sx]=color;
        }
    }
}
