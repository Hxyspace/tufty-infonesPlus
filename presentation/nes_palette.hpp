inline bool parse_palette(const char *id,Palette &value) {
    if(id) for(unsigned i=0;i<palette_count;++i) {
        const auto candidate=Palette(i);
        if(!std::strcmp(id,palette_id(candidate))) {value=candidate; return true;}
    }
    return false;
}
constexpr std::array<uint16_t,64> palette565(const std::array<uint32_t,64> &rgb) {
    std::array<uint16_t,64> result{};
    for(unsigned i=0;i<64;++i)
        result[i]=((rgb[i]>>8)&0xf800)|((rgb[i]>>5)&0x07e0)|((rgb[i]>>3)&0x001f);
    return result;
}
